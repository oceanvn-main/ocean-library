classdef BoxAssembly < OceanMath.Vision.Geometry.IGeometry
    % BOXASSEMBLY  Union of oriented boxes (constructive-solid-geometry union):
    %   the exact 3-D ground truth for procedural shapes (chairs, tables,
    %   stools...). Everything a shape-reconstruction experiment needs as
    %   ground truth is available EXACTLY, not approximated from a mesh:
    %     inside(P)        solid membership        -> voxel targets (Voxelizer)
    %     intersectRays    nearest surface hit     -> rendered images, silhouettes
    %     sampleSurface(n) points + normals on the UNION boundary -> Chamfer / F1 targets
    %
    % UNION SURFACE SAMPLING:
    %   Sample each part's surface uniformly by area, then keep a sample p of
    %   part i (outward normal n) iff
    %     (1) p + eps n lies outside EVERY part      -> p is on the union
    %         boundary. This rejects points buried inside another part AND
    %         face-to-face contact patches (a leg standing under a seat),
    %         whose outside neighbour p + eps n is inside the other part;
    %     (2) no part j < i contains p - eps n       -> when two parts share a
    %         COPLANAR face with the same outward direction, that patch is
    %         generated by both; only the lowest-index part keeps it, so it
    %         is not sampled with double density.
    %   Rejection keeps the accepted samples uniform by area on the union
    %   boundary (uniform sampling restricted to a subset).
    %
    % NOTE: toMesh() concatenates the part meshes; it is a faithful drawing of
    %   the solid but NOT a watertight union mesh (overlapping parts keep their
    %   interior faces). Use Voxelizer.fromInsideFunction(@asm.inside) +
    %   Cubify for a watertight approximation.
    %
    % USAGE:
    %   asm = OceanMath.Vision.Geometry.BoxAssembly({box1, box2, ...});
    %   [P, N] = asm.sampleSurface(3000, RandStream('mt19937ar','Seed',1));
    %   [t, N, partId] = asm.intersectRays(O, D);
    %   asm2 = asm.transformed(R, t);   [lo, hi] = asm.bounds();
    %
    % See also: OceanMath.Vision.Geometry.BoxGeometry, OceanMath.Geometry.Mesh.Voxelizer

    properties (SetAccess = private)
        Parts cell = {}     % cell array of BoxGeometry
    end

    properties
        ContactTolerance (1,1) double {mustBeNonnegative} = 1e-6
    end

    methods
        function obj = BoxAssembly(parts)
            arguments
                parts cell = {}
            end
            for i = 1:numel(parts)
                if ~isa(parts{i}, 'OceanMath.Vision.Geometry.BoxGeometry')
                    error('OceanMath:Vision:Geometry:BoxAssembly:BadPart', ...
                        'Part %d is a %s, expected BoxGeometry.', i, class(parts{i}));
                end
            end
            obj.Parts = parts(:).';
        end

        function n = numParts(obj)
            n = numel(obj.Parts);
        end

        % ---------------------------------------------------------------- %
        %  IGeometry contract
        % ---------------------------------------------------------------- %
        function [t, normal] = intersect(obj, rayOrigin, rayDir)
            arguments
                obj
                rayOrigin (3,1) double
                rayDir (3,1) double
            end
            [t, N] = obj.intersectRays(rayOrigin.', (rayDir / norm(rayDir)).');
            normal = N.';
        end

        function [vertices, faces] = toMesh(obj)
            meshes = cellfun(@(b) OceanMath.Geometry.Mesh.TriMesh.fromGeometry(b), obj.Parts, ...
                'UniformOutput', false);
            m = OceanMath.Geometry.Mesh.TriMesh.concatenate(meshes);
            vertices = m.Vertices.';
            faces = m.Faces.';
        end

        function normal = getNormal(obj, point)
            % Normal of the part whose surface is closest to the point.
            best = inf;
            normal = [0; 0; 0];
            for i = 1:numel(obj.Parts)
                b = obj.Parts{i};
                local = b.Rotation.' * (point - b.Center);
                gap = min(abs(abs(local) - b.HalfSize));
                if gap < best
                    best = gap;
                    normal = b.getNormal(point);
                end
            end
        end

        % ---------------------------------------------------------------- %
        %  Vectorised solid queries
        % ---------------------------------------------------------------- %
        function tf = inside(obj, P, tol)
            % INSIDE  (M x 1) logical: point in at least one part.
            arguments
                obj
                P (:,3) double
                tol (1,1) double = 0
            end
            tf = false(size(P, 1), 1);
            for i = 1:numel(obj.Parts)
                tf = tf | obj.Parts{i}.inside(P, tol);
            end
        end

        function [t, N, partId] = intersectRays(obj, O, D)
            % INTERSECTRAYS  Nearest hit over all parts. O, D: (P x 3).
            arguments
                obj
                O (:,3) double
                D (:,3) double
            end
            P = size(O, 1);
            t = inf(P, 1);
            N = zeros(P, 3);
            partId = zeros(P, 1);
            for i = 1:numel(obj.Parts)
                [ti, Ni] = obj.Parts{i}.intersectRays(O, D);
                closer = ~isnan(ti) & ti < t;
                t(closer) = ti(closer);
                N(closer, :) = Ni(closer, :);
                partId(closer) = i;
            end
            t(partId == 0) = NaN;
        end

        function [P, N] = sampleSurface(obj, n, stream)
            % SAMPLESURFACE  n points uniform by area on the UNION boundary,
            %   with outward unit normals (see class doc for the rejection rule).
            arguments
                obj
                n (1,1) double {mustBeInteger, mustBePositive}
                stream = []
            end
            areas = cellfun(@(b) b.surfaceArea(), obj.Parts);
            nParts = numel(obj.Parts);
            maxRounds = 50;
            poolP = cell(maxRounds, nParts);
            poolN = cell(maxRounds, nParts);
            accepted = 0;
            for round = 1:maxRounds
                % One round = 2n candidates spread over parts proportionally to
                % area, i.e. 2n uniform samples of the union of all part surfaces.
                counts = OceanMath.Vision.Geometry.BoxAssembly.multinomialCounts(areas, 2 * n, stream);
                for i = 1:nParts
                    if counts(i) == 0
                        continue;
                    end
                    [Pi, Ni] = obj.Parts{i}.sampleSurface(counts(i), stream);
                    outward = Pi + obj.ContactTolerance * Ni;   % just outside part i
                    inward  = Pi - obj.ContactTolerance * Ni;   % just inside part i
                    keep = true(counts(i), 1);
                    for j = [1:i-1, i+1:nParts]
                        keep = keep & ~obj.Parts{j}.inside(outward);            % rule (1)
                        if j < i
                            keep = keep & ~obj.Parts{j}.inside(inward);         % rule (2)
                        end
                    end
                    poolP{round, i} = Pi(keep, :);
                    poolN{round, i} = Ni(keep, :);
                    accepted = accepted + nnz(keep);
                end
                % Only complete rounds are pooled, so every part got its fair
                % share of candidates -- stopping mid-round would bias the result.
                if accepted >= n
                    break;
                end
            end
            if accepted < n
                error('OceanMath:Vision:Geometry:BoxAssembly:SamplingFailed', ...
                    'Only %d of %d surface samples accepted after %d rounds.', accepted, n, maxRounds);
            end
            P = vertcat(poolP{:});
            N = vertcat(poolN{:});
            % A uniformly random subset of uniform samples is still uniform.
            if isempty(stream)
                pick = randperm(accepted, n);
            else
                pick = randperm(stream, accepted, n);
            end
            P = P(pick, :);
            N = N(pick, :);
        end

        function v = volume(obj)
            % VOLUME  EXACT volume of the union (overlaps counted once), for
            %   parts that share one orientation (true for every
            %   FurnitureShapeFactory shape, before and after transformed()).
            %
            %   COORDINATE COMPRESSION: in the common box frame, the union is
            %   constant on every cell of the grid formed by ALL part face
            %   coordinates (per axis, the sorted unique breakpoints). So
            %     vol = sum over compressed cells of  [cell centre in union] * dx dy dz
            %   which is exact -- no sampling, no discretisation error.
            R = obj.Parts{1}.Rotation;
            for i = 2:numel(obj.Parts)
                if norm(obj.Parts{i}.Rotation - R, 'fro') > 1e-9
                    error('OceanMath:Vision:Geometry:BoxAssembly:MixedOrientation', ...
                        'Exact volume needs all parts to share one orientation.');
                end
            end
            lo = cell2mat(cellfun(@(b) (R.' * b.Center - b.HalfSize).', obj.Parts.', 'UniformOutput', false));
            hi = cell2mat(cellfun(@(b) (R.' * b.Center + b.HalfSize).', obj.Parts.', 'UniformOutput', false));
            bx = unique([lo(:,1); hi(:,1)]); by = unique([lo(:,2); hi(:,2)]); bz = unique([lo(:,3); hi(:,3)]);
            [cx, cy, cz] = ndgrid((bx(1:end-1) + bx(2:end)) / 2, (by(1:end-1) + by(2:end)) / 2, ...
                                  (bz(1:end-1) + bz(2:end)) / 2);
            [dx, dy, dz] = ndgrid(diff(bx), diff(by), diff(bz));
            C = [cx(:), cy(:), cz(:)];                       % cell centres, box frame
            covered = any(all(C >= reshape(lo.', 1, 3, []) & C <= reshape(hi.', 1, 3, []), 2), 3);
            v = sum(covered .* dx(:) .* dy(:) .* dz(:));
        end

        function [lo, hi] = bounds(obj)
            % BOUNDS  Axis-aligned bounding box (1 x 3 each) of all part corners.
            C = cell2mat(cellfun(@(b) b.corners(), obj.Parts.', 'UniformOutput', false));
            lo = min(C, [], 1);
            hi = max(C, [], 1);
        end

        function asm = transformed(obj, R, t)
            % TRANSFORMED  Rigid motion x -> R x + t applied to every part.
            arguments
                obj
                R (3,3) double
                t (3,1) double = [0; 0; 0]
            end
            parts = cellfun(@(b) b.transformed(R, t), obj.Parts, 'UniformOutput', false);
            asm = OceanMath.Vision.Geometry.BoxAssembly(parts);
            asm.ContactTolerance = obj.ContactTolerance;
        end

        function asm = scaled(obj, s)
            parts = cellfun(@(b) b.scaled(s), obj.Parts, 'UniformOutput', false);
            asm = OceanMath.Vision.Geometry.BoxAssembly(parts);
            asm.ContactTolerance = obj.ContactTolerance * s;
        end

        function asm = normalized(obj)
            % NORMALIZED  Centre the bounding box at the origin and scale so the
            %   largest half-extent is 1 (the shape fits [-1,1]^3 tightly).
            [lo, hi] = obj.bounds();
            moved = obj.transformed(eye(3), -((lo + hi) / 2).');
            asm = moved.scaled(1 / max((hi - lo) / 2));
        end
    end

    methods (Static, Access = private)
        function counts = multinomialCounts(weights, total, stream)
            % Draw 'total' categorical samples with P(i) ~ weights(i); return counts.
            cdf = cumsum(weights(:)) / sum(weights);
            cdf(end) = 1;
            if isempty(stream)
                u = rand(total, 1);
            else
                u = rand(stream, total, 1);
            end
            counts = accumarray(discretize(u, [0; cdf]), 1, [numel(weights) 1]);
        end
    end
end
