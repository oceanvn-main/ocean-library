function types = storeTypes()
% STORETYPES  Declared component types used by the Store tests (one of each class and kind).
%   Position  double 1x2, L        (value)       Velocity  double 1x2, L T^-1 (value)
%   Charge    double 1x1, E        (linear)      Level     double 1x2, L      (linear, two columns)
%   Born      double 1x1, T        (clock)       Name      string 1x1         (value)
%   Flags     logical 1x3          (value)
D = OceanAgents.World.Guard.Dimension;
T = @(varargin) OceanAgents.World.Guard.ComponentType(varargin{:});
types = struct( ...
    'Position', T('Width', 2, 'Dimension', D.L()), ...
    'Velocity', T('Width', 2, 'Dimension', D.L() / D.T()), ...
    'Charge', T('Kind', "linear", 'Dimension', D.E()), ...
    'Level', T('Kind', "linear", 'Width', 2, 'Dimension', D.L()), ...
    'Born', T('Kind', "clock", 'Dimension', D.T()), ...
    'Name', T('Class', "string"), ...
    'Flags', T('Class', "logical", 'Width', 3));
end
