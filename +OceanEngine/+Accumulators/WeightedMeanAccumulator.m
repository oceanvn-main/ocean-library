classdef WeightedMeanAccumulator < OceanEngine.Accumulators.AbstractAccumulator
    % WEIGHTEDMEANACCUMULATOR  Online weighted mean & importance sampling accumulator.
    %
    %   Implements the incremental weighted mean update rule (Sutton & Barto Eq. 5.8):
    %     C_n = C_{n-1} + W_n
    %     V_n = V_{n-1} + (W_n / C_n) * (X_n - V_{n-1})
    %
    %   Supports scalar, vector, and 2D matrix (states x actions) lookup tables
    %   with fast direct subscript indexing updates:
    %     acc.update(G, W, s_idx, a_idx)
    %
    %   Package: OceanEngine.Accumulators
    %   Reference: Sutton & Barto (2018) Chapter 5, Section 5.6
    %
    %   See also: OceanEngine.Accumulators.AbstractAccumulator
    %             OceanEngine.Accumulators.IAccumulator

    methods
        function obj = WeightedMeanAccumulator(shape, opts)
            % WEIGHTEDMEANACCUMULATOR Constructor.
            %
            % Inputs:
            %   shape          - Array dimensions [rows, cols] or scalar N (default [1 1])
            %   opts.InitValue - Initial value for value table (default 0.0)
            arguments
                shape             double = [1 1]
                opts.InitValue    (1,1) double = 0.0
            end
            obj@OceanEngine.Accumulators.AbstractAccumulator(shape, 'InitValue', opts.InitValue);
            obj.reset();
        end

        function meta = getMetadata(obj)
            % GETMETADATA  Returns pedagogical reflection metadata.
            meta = struct(...
                'Name', 'Weighted Mean Accumulator', ...
                'SymbolicLatex', 'V_n = V_{n-1} + \frac{W_n}{C_n} (X_n - V_{n-1})', ...
                'Formula', 'V_n = V_{n-1} + \frac{W_n}{C_n} (X_n - V_{n-1})', ...
                'TextbookRef', 'Sutton & Barto (2018) Eq. 5.8', ...
                'Shape', obj.Shape, ...
                'Description', 'Incremental weighted average & importance sampling accumulator.', ...
                'Symbols', [ ...
                    struct('Symbol', 'V_n', 'Description', 'Estimated value/mean table at step n'), ...
                    struct('Symbol', 'V_{n-1}', 'Description', 'Previous estimated value table at step n-1'), ...
                    struct('Symbol', 'W_n', 'Description', 'Importance sampling weight of current sample'), ...
                    struct('Symbol', 'C_n', 'Description', 'Cumulative weight sum table at step n'), ...
                    struct('Symbol', 'X_n', 'Description', 'Sample return/observation at step n') ...
                ] ...
            );
        end

        function spec = getDiagramSpec(obj)
            % GETDIAGRAMSPEC  Returns Pillar 3 diagram representation (Ports & Canvas Symbol).
            spec = struct(...
                'Inputs', struct(...
                    'sample', struct('Domain', 'sample-stream',      'DType', 'real', 'Shape', obj.Shape), ...
                    'weight', struct('Domain', 'importance-weight',  'DType', 'real', 'Shape', [1 1]), ...
                    'index',  struct('Domain', 'state-action-index', 'DType', 'int',  'Shape', [1 2])...
                ), ...
                'Outputs', struct(...
                    'value',      struct('Domain', 'estimated-mean', 'DType', 'real', 'Shape', obj.Shape), ...
                    'cum_weight', struct('Domain', 'weight-sum',     'DType', 'real', 'Shape', obj.Shape)...
                ), ...
                'DiagramSymbol', struct(...
                    'Style',     'SimulinkBlock', ...
                    'LabelText', 'Weighted Mean Accumulator', ...
                    'Formula',   'V_n = V_{n-1} + \frac{W_n}{C_n} (X_n - V_{n-1})', ...
                    'IconPath',  '' ...
                )...
            );
        end
    end

    methods (Access = protected)
        function updateFullArray(obj, sample, weight)
            obj.WeightTable = obj.WeightTable + weight;
            valid_mask = obj.WeightTable > 0;
            if any(valid_mask, 'all')
                step_size = weight ./ obj.WeightTable(valid_mask);
                obj.ValueTable(valid_mask) = obj.ValueTable(valid_mask) + ...
                    step_size .* (sample - obj.ValueTable(valid_mask));
            end
        end

        function updateIndexed(obj, sample, weight, idx)
            obj.WeightTable(idx) = obj.WeightTable(idx) + weight;
            c_val = obj.WeightTable(idx);
            if c_val > 0
                obj.ValueTable(idx) = obj.ValueTable(idx) + ...
                    (weight / c_val) * (sample - obj.ValueTable(idx));
            end
        end

        function updateSubscript2D(obj, sample, weight, s_idx, a_idx)
            obj.WeightTable(s_idx, a_idx) = obj.WeightTable(s_idx, a_idx) + weight;
            c_val = obj.WeightTable(s_idx, a_idx);
            if c_val > 0
                obj.ValueTable(s_idx, a_idx) = obj.ValueTable(s_idx, a_idx) + ...
                    (weight / c_val) * (sample - obj.ValueTable(s_idx, a_idx));
            end
        end
    end
end
