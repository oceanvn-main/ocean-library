classdef DiscountingAwareWeightedISWeighting < OceanStats.RL.MonteCarlo.Weighting.IImportanceWeighting
    % DISCOUNTINGAWAREWEIGHTEDISWEIGHTING Discounting-Aware Weighted IS Scheme.
    %
    % Implements Section 5.8 Equation 5.10 from Sutton & Barto (2nd Ed.), treating
    % discounting gamma as partial termination to scale flat partial returns
    % G_bar_{t:h} by truncated importance sampling ratios rho_{t:h-1}, normalized
    % by the sum of truncated weights W^{\text{disc}}_t.
    %
    % Equation 5.10:
    %   V(s) = \frac{\sum_{t \in \mathcal{J}(s)} G^{\text{disc}}_t}{\sum_{t \in \mathcal{J}(s)} W^{\text{disc}}_t}
    %
    % where:
    %   G^{\text{disc}}_t = (1-\gamma) \sum_{h=t+1}^{T-1} \gamma^{h-t-1} \rho_{t:h-1} \bar{G}_{t:h}
    %                     + \gamma^{T-t-1} \rho_{t:T-1} \bar{G}_{t:T}
    %   W^{\text{disc}}_t = (1-\gamma) \sum_{h=t+1}^{T-1} \gamma^{h-t-1} \rho_{t:h-1}
    %                     + \gamma^{T-t-1} \rho_{t:T-1}
    %
    % Package: OceanStats.RL.MonteCarlo.Weighting
    % Reference: Sutton & Barto (2018) Section 5.8, Eq 5.10

    methods
        function update(~, accum, G_disc, W_disc, s_idx, a_idx)
            % G_disc - composite return numerator sum
            % W_disc - composite weight denominator sum
            if W_disc <= 0, return; end

            val = G_disc / W_disc;

            if nargin < 6 || isempty(a_idx) || a_idx == 0
                accum.update(val, W_disc, s_idx);
            else
                accum.update(val, W_disc, s_idx, a_idx);
            end
        end
    end

