    % Reference: Sutton & Barto (2018) Section 5.6, Eq 5.6

    methods
        function update(~, accum, G, W, s_idx, a_idx)
            if nargin < 6 || isempty(a_idx) || a_idx == 0
                accum.update(G, W, s_idx);
            else
                accum.update(G, W, s_idx, a_idx);
            end
        end
    end

