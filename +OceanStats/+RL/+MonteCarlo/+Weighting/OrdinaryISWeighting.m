classdef OrdinaryISWeighting < OceanStats.RL.MonteCarlo.Weighting.IImportanceWeighting
    % ORDINARYISWEIGHTING Ordinary Importance Sampling Weighting Scheme.
    %
    % Implements unweighted empirical mean of importance-weighted returns
    % (Sutton & Barto 2nd Ed., Equation 5.5):
    %   V(s) = \frac{\sum_{t \in \mathcal{J}(s)} W_t G_t}{|\mathcal{J}(s)|}
    %
    % Package: OceanStats.RL.MonteCarlo.Weighting
    % Reference: Sutton & Barto (2018) Section 5.5, Eq 5.5

    methods
        function update(~, accum, G, W, s_idx, a_idx)
            if nargin < 6 || isempty(a_idx) || a_idx == 0
                accum.update(W * G, 1.0, s_idx);
            else
                accum.update(W * G, 1.0, s_idx, a_idx);
            end
        end
    end

