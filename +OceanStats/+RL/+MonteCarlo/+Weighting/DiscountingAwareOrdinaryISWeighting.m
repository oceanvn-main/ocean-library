classdef DiscountingAwareOrdinaryISWeighting < OceanStats.RL.MonteCarlo.Weighting.IImportanceWeighting
    % DISCOUNTINGAWAREORDINARYISWEIGHTING Discounting-Aware Ordinary IS Scheme.
    %
    % Implements Section 5.8 Equation 5.9 from Sutton & Barto (2nd Ed.), treating
    % discounting gamma as partial termination to scale flat partial returns
    % G_bar_{t:h} by truncated importance sampling ratios rho_{t:h-1}.
    %
    % Equation 5.9:
    %   V(s) = \frac{\sum_{t \in \mathcal{J}(s)} G^{\text{disc}}_t}{|\mathcal{J}(s)|}
    %
    % where:
    %   G^{\text{disc}}_t = (1-\gamma) \sum_{h=t+1}^{T-1} \gamma^{h-t-1} \rho_{t:h-1} \bar{G}_{t:h}
    %                     + \gamma^{T-t-1} \rho_{t:T-1} \bar{G}_{t:T}
    %
    % Package: OceanStats.RL.MonteCarlo.Weighting
    % Reference: Sutton & Barto (2018) Section 5.8, Eq 5.9

    methods
        function update(~, accum, G_disc, ~, s_idx, a_idx)
            % G_disc - pre-computed discounting-aware return scalar G_disc_t
            if nargin < 6 || isempty(a_idx) || a_idx == 0
                accum.update(G_disc, 1.0, s_idx);
            else
                accum.update(G_disc, 1.0, s_idx, a_idx);
            end
        end
    end

