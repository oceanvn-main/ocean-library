%% validate_pitch_threshold  Choose PitchContour's YIN voicing threshold from data.
%
%   The YIN paper's absolute threshold 0.1 gave low voicing recall on FSDD
%   (critic round 1 / B1 report). This script sweeps the threshold and compares the
%   Ocean voicing decision with librosa.pyin (HMM-smoothed, used here only as an
%   external reference) on real audio:
%     * SELECTION on the three TRAIN speakers (seeded sample of files),
%     * CONFIRMATION on the held-out speaker theo (not used for the choice).
%   Metrics per threshold: voicing precision / recall / F1 against pyin, and the
%   gross pitch error rate (> 20 % deviation) on frames both call voiced.
%   Writes Results/Speech/pitch_threshold_validation.md. Consumer script only.

here = fileparts(mfilename('fullpath'));
repo = fileparts(fileparts(fileparts(here)));
addpath(repo);
py = fullfile(repo, '.venv', 'Scripts', 'python.exe');
thresholds = [0.05 0.1 0.15 0.2 0.25 0.3 0.35 0.4 0.5];
perSpeaker = 20;
fmin = 50; fmax = 400;

man = OceanNLP.Speech.Data.SpeechManifest.fromFSDD();
E = man.Entries;
rs = RandStream('mt19937ar', 'Seed', 11);
pick = @(spk) find(E.Speaker == spk);
sets = struct('Name', {"train speakers (selection)", "theo (held out, confirmation)"}, 'Idx', {[], []});
for spk = ["jackson", "nicolas", "yweweler"]
    i = pick(spk); sets(1).Idx = [sets(1).Idx; i(randperm(rs, numel(i), perSpeaker))];
end
i = pick("theo"); sets(2).Idx = i(randperm(rs, numel(i), perSpeaker));

out = string(tempname);
job = struct('out', out, 'fmin', fmin, 'fmax', fmax, 'files', struct('key', {}, 'path', {}));
allIdx = [sets(1).Idx; sets(2).Idx];
for k = 1:numel(allIdx)
    job.files(end + 1) = struct('key', sprintf('f%03d', k), 'path', char(man.resolve(allIdx(k))));
end
jf = out + ".json";
fid = fopen(jf, 'w'); fwrite(fid, jsonencode(job)); fclose(fid);
[st, msg] = system(sprintf('"%s" "%s" "%s"', py, fullfile(here, 'validate_pitch_threshold.py'), jf));
assert(st == 0, msg);
ver = jsondecode(fileread(fullfile(out, 'versions.json')));

rows = {};
for s = 1:2
    keys = arrayfun(@(k) sprintf('f%03d', k), find(ismember(allIdx, sets(s).Idx)), 'UniformOutput', false);
    idx = allIdx(ismember(allIdx, sets(s).Idx));
    for thr = thresholds
        tp = 0; fp = 0; fn = 0; both = 0; gross = 0;
        for k = 1:numel(idx)
            w = OceanNLP.Speech.Core.Waveform.read(man.resolve(idx(k)));
            pc = OceanNLP.Speech.Features.PitchContour(w.SampleRate, 'MinF0', fmin, 'MaxF0', fmax, ...
                'VoicingThreshold', thr).forward(w).Values;
            pv = OceanData.Adapters.NpyReader.read(fullfile(out, keys{k} + "_voiced.npy"))' > 0;
            pf = OceanData.Adapters.NpyReader.read(fullfile(out, keys{k} + "_f0.npy"))';
            T = min(numel(pv), size(pc, 2));
            ov = pc(1, 1:T) > 0; pv = pv(1:T); pf = pf(1:T);
            tp = tp + nnz(ov & pv); fp = fp + nnz(ov & ~pv); fn = fn + nnz(~ov & pv);
            b = ov & pv;
            both = both + nnz(b);
            gross = gross + nnz(abs(pc(1, b) - pf(b)) ./ pf(b) > 0.2);
        end
        P = tp / max(tp + fp, 1); R = tp / max(tp + fn, 1); F1 = 2 * P * R / max(P + R, eps);
        rows(end + 1, :) = {sets(s).Name, thr, P, R, F1, gross / max(both, 1), both}; %#ok<SAGROW>
    end
end
Tb = cell2table(rows, 'VariableNames', ["Set", "Threshold", "Precision", "Recall", "F1", "GrossErrorRate", "BothVoiced"]);
sel = Tb(Tb.Set == sets(1).Name, :);
maxGross = 0.10;     % a voicing decision that admits > 10 % wrong-pitch frames is not useful
cand = sel(sel.GrossErrorRate <= maxGross, :);
[~, ib] = max(cand.F1);
best = cand.Threshold(ib);
[~, ibF] = max(sel.F1);
disp(Tb);
fprintf('selected threshold (max F1 with gross error <= %.2f, train speakers): %.2f\n', maxGross, best);

lines = ["# PitchContour voicing threshold vs librosa.pyin", "", ...
    "Generated by `Experiments/Scripts/Speech/validate_pitch_threshold.m` on " + string(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')) + ...
    " (librosa " + string(ver.librosa) + "). Real FSDD audio, " + perSpeaker + " seeded files per speaker; range " + fmin + "–" + fmax + " Hz; frames aligned as in `feature_validation.md`.", "", ...
    "Selection uses only the train speakers; theo is reported as a held-out confirmation. pyin is HMM-smoothed, so it is a reference, not ground truth.", "", ...
    "| Set | Threshold | Precision | Recall | F1 | Gross error (both voiced) | Both-voiced frames |", "| --- | --- | --- | --- | --- | --- | --- |"];
for r = 1:height(Tb)
    lines(end + 1) = sprintf("| %s | %.2f | %.3f | %.3f | %.3f | %.3f | %d |", Tb.Set(r), Tb.Threshold(r), Tb.Precision(r), ...
        Tb.Recall(r), Tb.F1(r), Tb.GrossErrorRate(r), Tb.BothVoiced(r)); %#ok<SAGROW>
end
lines(end + 1) = "";
lines(end + 1) = sprintf("**Selected threshold: %.2f** = highest voicing F1 on the train speakers among thresholds whose gross pitch error stays <= %.0f %%. Unconstrained F1 peaks at %.2f, but there the gross pitch error is %.1f %%: the extra voiced frames mostly carry wrong pitch. This selection rule was fixed after inspecting a first sweep that used F1 alone; theo was not used for the choice.", ...
    best, 100 * maxGross, sel.Threshold(ibF), 100 * sel.GrossErrorRate(ibF));
lines(end + 1) = "";
lines(end + 1) = "The YIN paper's 0.1 (de Cheveigné & Kawahara 2002) targets gross pitch error, not voicing recall; on FSDD it marks only about half of pyin's voiced frames as voiced.";
outDir = fullfile(repo, 'Results', 'Speech');
fid = fopen(fullfile(outDir, 'pitch_threshold_validation.md'), 'w');
fwrite(fid, strjoin(lines, newline)); fclose(fid);
