function run = runChangingMaze(kind,configuration)
% RUNCHANGINGMAZE Execute one time-aligned nonstationary Dyna experiment.
arguments
    kind (1,1) string {mustBeMember(kind,["dyna-q","dyna-q+"])}
    configuration (1,1) struct
end
env = DynaExperiments.ChangingMazeEnv( ...
    'ChangeStep',configuration.ChangeStep, ...
    'InitialBlockedRC',configuration.InitialBlockedRC, ...
    'ChangedBlockedRC',configuration.ChangedBlockedRC);
observer = OceanStats.RL.Dyna.Observers.Recorder();
if kind == "dyna-q"
    learner = OceanStats.RL.Dyna.Factory.dynaQ(env,'Alpha',configuration.Alpha, ...
        'Epsilon',configuration.Epsilon,'Gamma',configuration.Gamma, ...
        'PlanningSteps',configuration.PlanningSteps,'Seed',configuration.Seed, ...
        'Observer',observer);
else
    learner = OceanStats.RL.Dyna.Factory.dynaQPlus(env,'Kappa',configuration.Kappa, ...
        'Alpha',configuration.Alpha,'Epsilon',configuration.Epsilon, ...
        'Gamma',configuration.Gamma,'PlanningSteps',configuration.PlanningSteps, ...
        'Seed',configuration.Seed,'Observer',observer);
end
% Each episode is bounded, while the environment's change clock deliberately
% persists across resets. Extra interactions are discarded only for plotting.
result = learner.run('NumEpisodes',configuration.NumEpisodes, ...
    'MaxStepsPerEpisode',configuration.MaxStepsPerEpisode);
n = min(configuration.Horizon,numel(observer.Transitions));
reward = zeros(configuration.Horizon,1);
for t = 1:n
    reward(t) = observer.Transitions{t}.Reward;
end
if n < configuration.Horizon
    warning('OceanExperiments:Dyna:ShortRun', ...
        'Run produced %d of %d requested interactions.',n,configuration.Horizon);
end
run = struct('Algorithm',kind,'CumulativeReward',cumsum(reward), ...
    'Reward',reward,'InteractionsObserved',n,'Result',result, ...
    'Environment',env.inspect());
end
