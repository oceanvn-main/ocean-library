"""
EXP_SPECTRAL_CLUSTERING  Recreation of ESL Figure 14.29 Spectral Clustering (Python Production Version).

   DATASET:        450 points, 3 concentric circles (r=1, 2.8, 5) with N(0, 0.25^2) noise
   MODEL:          Unnormalized Spectral Clustering (using Scikit-Learn)
   ASSUMPTIONS:    Using the nearest_neighbors affinity matrix.
   REPRODUCIBILITY: np.random.seed(42) at top of script
"""

# %%
import numpy as np
import matplotlib.pyplot as plt
from sklearn.cluster import SpectralClustering

# Reproducibility
np.random.seed(42)

#%% === 1. Data Loading ===
N_per_cluster = 150
K = 3
N = N_per_cluster * K
radii = [1, 2.8, 5]
noise_std = 0.25


X = np.zeros((N, 2)) #Default float64
Y_true = np.zeros(N, dtype=int)

# %%

for k, r in enumerate(radii):
    #k=0, filsl rows 0 to 150
    idx = slice(k * N_per_cluster, (k + 1) * N_per_cluster)
    angles = np.random.uniform(0, 2 * np.pi, N_per_cluster)
    
    X[idx, 0] = r * np.cos(angles) + np.random.normal(0, noise_std, N_per_cluster)
    X[idx, 1] = r * np.sin(angles) + np.random.normal(0, noise_std, N_per_cluster)
    Y_true[idx] = k

# === 2. Model Configuration & Training ===
num_neighbors = 10
sc = SpectralClustering(
    n_clusters=K,
    affinity='nearest_neighbors',
    n_neighbors=num_neighbors,
    assign_labels='kmeans',
    random_state=42
)

# Fit the model
labels = sc.fit_predict(X)

from scipy.linalg import eigh

# Extract the affinity matrix W generated by Scikit-Learn
W = sc.affinity_matrix_.toarray()

# Compute the Unnormalized Graph Laplacian (L = D - W) to match MATLAB exactly
D = np.diag(np.sum(W, axis=1))
L = D - W

# Compute Eigenvalues and Eigenvectors
# eigh is highly optimized for symmetric matrices and returns sorted results
eigenvalues, eigenvectors = eigh(L)

# The first eigenvector is a constant (eigenvalue 0), so we take the 2nd and 3rd
Z2 = eigenvectors[:, 1]
Z3 = eigenvectors[:, 2]

# Styling
plt.style.use('ggplot')
colors = ['#1f77b4', '#ff7f0e', '#2ca02c']

fig, axes = plt.subplots(2, 2, figsize=(14, 12)) 
fig.suptitle('Spectral Clustering (Scikit-Learn Production Implementation)', fontsize=16)

# Panel 1: Top Left - Data points
ax1 = axes[0, 0]
for k in range(K):
    ax1.scatter(X[labels == k, 0], X[labels == k, 1], c=[colors[k]], label=f'Predicted Cluster {k+1}', s=30, edgecolor='white', alpha=0.9)
ax1.set_title('Original Data (Colored by Predictions)')
ax1.set_xlabel('x1')
ax1.set_ylabel('x2')
ax1.axis('equal')
ax1.legend()

# Panel 2: Top Right - 15 smallest eigenvalues
ax2 = axes[0, 1]
ax2.plot(range(1, 16), eigenvalues[:15], 'o', markersize=6, color=colors[0], markeredgecolor='white')
ax2.axhline(0, color='gray', linestyle='--')
ax2.set_title('Eigenvalues')
ax2.set_xlabel('Number')
ax2.set_ylabel('Eigenvalue')

# Panel 3: Bottom Left - 2nd and 3rd smallest eigenvectors
ax3 = axes[1, 0]

# Sort data by cluster to match ESL's block-wise plot
sort_idx = np.argsort(labels)
Z2_sorted = Z2[sort_idx]
Z3_sorted = Z3[sort_idx]
labels_sorted = labels[sort_idx]

for k in range(K):
    idx = np.where(labels_sorted == k)[0]
    ax3.scatter(idx, Z2_sorted[idx] + 0.15, c=[colors[k]], s=15, edgecolor='white', alpha=0.9)
    ax3.scatter(idx, Z3_sorted[idx] - 0.15, c=[colors[k]], s=15, edgecolor='white', alpha=0.9)

ax3.axhline(0.15, color='gray', linestyle='--')
ax3.axhline(-0.15, color='gray', linestyle='--')
ax3.set_title('Eigenvectors (Sorted by Cluster)')
ax3.set_xlabel('Index')
ax3.set_yticks([]) # Hide artificial y-ticks

# Panel 4: Bottom Right - Spectral Clustering (Z2 vs Z3)
ax4 = axes[1, 1]
for k in range(K):
    ax4.scatter(Z2[labels == k], Z3[labels == k], c=[colors[k]], label=f'Cluster {k+1}', s=30, edgecolor='white', alpha=0.9)
ax4.set_title('Spectral Clustering (Spectral Domain)')
ax4.set_xlabel('Second Smallest Eigenvector (Z2)')
ax4.set_ylabel('Third Smallest Eigenvector (Z3)')
ax4.axis('equal')
ax4.legend()

plt.tight_layout()
plt.show()

import os
os.makedirs('Results/Python', exist_ok=True)
plt.savefig('Results/Python/exp_spectral_clustering_py.png', dpi=300)
print("\n=== EXPERIMENT SUMMARY ===")
print(f"  Dataset       : 3 Concentric Circles (N={N}, p=2)")
print("  Model         : SpectralClustering (Scikit-Learn)")
print(f"  Graph         : Nearest Neighbors (k={num_neighbors})")
print(f"  Zero EigVal   : {eigenvalues[0]:.4f}")
print(f"  Cluster Sizes : {np.sum(labels == 0)}, {np.sum(labels == 1)}, {np.sum(labels == 2)}")
print("==========================")
