plot(ax1a, x, Sy_spline, '-', ...
    'Color', C.Primary, 'LineWidth', 2.2, ...
    'DisplayName', 'Spline  S*y');

title(ax1a, 'Smoothing Spline — Data & Fits', ...
    'Color', C.Text, 'FontSize', 13);
ylabel(ax1a, 'y', 'Color', C.Text);
legend(ax1a, 'Location', 'northwest', 'TextColor', C.Text, ...
    'EdgeColor', 'none', 'Color', C.Background);

% --- Subplot 2: Identity check -------------------------------------------
ax1b = subplot(2, 1, 2, 'Parent', fig1);
viz.styleAxes(ax1b);
hold(ax1b, 'on');

plot(ax1b, x, Sy_spline, '-', ...
    'Color', C.Primary, 'LineWidth', 3, ...
    'DisplayName', 'S*y  (LHS)');

plot(ax1b, x, rhs_spline, ':', ...
    'Color', C.Boundary, 'LineWidth', 2.5, ...
    'DisplayName', 'y\_hat + S*r  (RHS)');

title(ax1b, sprintf('Identity Check: max|S*y - (y\\_hat + S*r)| = %.2e', diff_spline), ...
    'Color', C.Text, 'FontSize', 12);
xlabel(ax1b, 'x', 'Color', C.Text);
ylabel(ax1b, 'Smoothed value', 'Color', C.Text);
legend(ax1b, 'Location', 'northwest', 'TextColor', C.Text, ...
    'EdgeColor', 'none', 'Color', C.Background);

sgtitle(fig1, 'Ex 9.1: Linear Reproduction — Smoothing Spline', ...
    'Color', C.Text, 'FontSize', 15, 'FontWeight', 'bold');

