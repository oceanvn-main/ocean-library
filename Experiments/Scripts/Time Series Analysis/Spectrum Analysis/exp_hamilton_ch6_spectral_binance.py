"""
EXP_HAMILTON_CH6_SPECTRAL_BINANCE.PY

Python Phase 2 counterpart for Hamilton Chapter 6 Spectral Analysis replication.
Ingests Parquet data generated by MATLAB Phase 1 (binance_btc_daily_hamilton.parquet),
computes sample periodograms, evaluates theoretical filter transfer functions,
fits AR models, and verifies spectral energy conservation (Parseval's identity).

Author: Ocean Library   Date: 2026-09-29
"""

import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy import signal
from statsmodels.tsa.ar_model import AutoReg

def main():
    print("=====================================================================")
    print("   PYTHON PHASE 2: HAMILTON CH.6 SPECTRAL ANALYSIS (BINANCE DATA)    ")
    print("=====================================================================\n")

    parquet_path = os.path.join("lake", "processed", "binance_btc_daily_hamilton.parquet")
    if not os.path.exists(parquet_path):
        # Fallback to local execution path if run from root
        parquet_path = os.path.join("Experiments", "Scripts", "Time Series Analysis", "Spectrum Analysis", "lake", "processed", "binance_btc_daily_hamilton.parquet")

    if not os.path.exists(parquet_path):
        raise FileNotFoundError(f"Parquet dataset not found at {parquet_path}. Run MATLAB Phase 1 first.")

    print(f"[Step 2.1] Loading Parquet dataset from: {parquet_path}")
    df = pd.read_parquet(parquet_path)
    print(f"   - Total rows: {len(df)}")
    print(f"   - Columns: {list(df.columns)}")

    # Extract cleaned numpy arrays
    y_level = df["LogLevel"].values
    x_ret   = df["LogReturn"].dropna().values
    w_growth = df["Growth30D"].dropna().values

    # Step 2.2: Compute Periodograms via NumPy / SciPy
    print("\n[Step 2.2] Computing Sample Periodograms via SciPy...")
    f_y, P_y = signal.periodogram(y_level - np.mean(y_level), fs=1.0, scaling='spectrum')
    f_x, P_x = signal.periodogram(x_ret - np.mean(x_ret),     fs=1.0, scaling='spectrum')
    f_w, P_w = signal.periodogram(w_growth - np.mean(w_growth), fs=1.0, scaling='spectrum')

    # Convert cycles/sample to radians/sample: omega = 2 * pi * f
    w_y = 2 * np.pi * f_y
    w_x = 2 * np.pi * f_x
    w_w = 2 * np.pi * f_w

    # Theoretical Filter Transfer Functions
    # 1-day differencing: h_x(w) = 4 * sin^2(w / 2)
    # 30-day differencing: h_w(w) = 4 * sin^2(30 * w / 2)
    h_diff = 4 * np.sin(w_x / 2.0)**2
    h_30d  = 4 * np.sin(30.0 * w_x / 2.0)**2

    # Step 2.3: Fit AR(4) Model via statsmodels
    print("\n[Step 2.3] Fitting AutoReg AR(4) Model on Log Returns...")
    ar_fit = AutoReg(x_ret, lags=4).fit()
    print(f"   - AR Coeffs: {ar_fit.params}")
    print(f"   - Innovation Variance sigma_e^2: {ar_fit.sigma2:.6f}")

    # Theoretical AR Spectrum: S(w) = sigma^2 / (2*pi * |1 - sum(phi_k * e^{-i k w})|^2)
    coeffs = ar_fit.params[1:] # Exclude intercept
    poly_terms = 1.0 - sum(c * np.exp(-1j * (k + 1) * w_x) for k, c in enumerate(coeffs))
    pop_spectrum_ar = (ar_fit.sigma2 / (2 * np.pi)) / (np.abs(poly_terms)**2)

    # Step 2.4: Verify Parseval's Spectral Energy Identity
    print("\n[Step 2.4] Verifying Parseval's Identity in Python...")
    # Periodogram integral over [0, pi]
    dw = w_x[1] - w_x[0]
    # Periodogram I(w) normalization factor
    I_x_raw = (1.0 / (2 * np.pi * len(x_ret))) * np.abs(np.fft.rfft(x_ret - np.mean(x_ret)))**2
    area_Ix = np.sum(I_x_raw[1:-1]) * 2 * dw + I_x_raw[0] * dw + I_x_raw[-1] * dw
    var_x = np.var(x_ret, ddof=0)

    print(f"   - Integrated Periodogram Area: {area_Ix:.6f}")
    print(f"   - Sample Variance Var(x_t):   {var_x:.6f}")
    print(f"   - Parseval Absolute Error:    {abs(area_Ix - var_x):.4e}")

    # Step 2.5: Plotting Output
    print("\n[Step 2.5] Rendering Python Verification Plots...")
    plt.style.use('dark_background')
    fig, axes = plt.subplots(3, 1, figsize=(10, 8), sharex=True)

    axes[0].plot(w_y, 10 * np.log10(P_y + 1e-12), color='#1f77b4', label='I_y(w) (Raw Log Level)')
    axes[0].set_title("Hamilton Fig 6.4 Python Analog: Raw Level Periodogram (Low-Frequency Dominance)")
    axes[0].set_ylabel("Power (dB)")
    axes[0].legend(loc='upper right')

    axes[1].plot(w_x, 10 * np.log10(P_x + 1e-12), color='#ff7f0e', label='I_x(w) (1-Day Return)')
    axes[1].plot(w_x, 10 * np.log10(pop_spectrum_ar + 1e-12), color='#2ca02c', linestyle='--', label='Theoretical AR(4) Spectrum')
    axes[1].set_title("Hamilton Fig 6.5 Python Analog: 1-Day Return Periodogram & AR Spectrum")
    axes[1].set_ylabel("Power (dB)")
    axes[1].legend(loc='upper right')

    axes[2].plot(w_w, 10 * np.log10(P_w + 1e-12), color='#d62728', label='I_w(w) (30-Day Growth)')
    axes[2].set_title("Hamilton Fig 6.6 Python Analog: 30-Day Growth Periodogram (Filter Ripples & Nulls)")
    axes[2].set_xlabel("Frequency omega (rad/sample)")
    axes[2].set_ylabel("Power (dB)")
    axes[2].legend(loc='upper right')

    plt.tight_layout()
    out_img = os.path.join("lake", "processed", "python_hamilton_spectral.png")
    os.makedirs(os.path.dirname(out_img), exist_ok=True)
    plt.savefig(out_img, dpi=150)
    print(f"   - Saved verification plot to: {out_img}")

    print("\n=====================================================================")
    print("   PYTHON PHASE 2 HAMILTON SPECTRAL ANALYSIS COMPLETE   ")
    print("=====================================================================")

if __name__ == "__main__":
    main()
